#!/usr/bin/env python3
"""3D models of furniture: assets/3d/models/*.obj -> assets/js/visit3d-models.js.

The furniture models of the 3D visit (assets/js/visit3d.js: model(g, 'Bathroom_Toilet', ...))
are OBJ files in assets/3d/models/, taken from a pack kept in 3d-sources/ (see README.md,
"3D visit"). This script:

- with --add <pack>/<Name>.obj ...: copies those models into assets/3d/models/, reduced to
  what the visit uses: vertices (4 decimals), material names and faces (no normals, texture
  coordinates or material library: the visit computes flat normals and sets the materials);
- writes assets/js/visit3d-models.js, the module imported by visit3d.js, with every model as
  OBJ text (short lines).

With --check it changes nothing and fails if the module is not up to date (the deployment
workflow runs it before building the site).

Usage:
  python3 scripts/models.py --add 3d-sources/quaternius/OBJ/Bathroom_Toilet.obj
  python3 scripts/models.py
  python3 scripts/models.py --check
Standard library only.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MODELS = REPO_ROOT / "assets" / "3d" / "models"
MODULE = REPO_ROOT / "assets" / "js" / "visit3d-models.js"


def clean(text: str) -> str:
    """OBJ reduced to vertices, objects, material names and faces (vertex indices only)."""
    out = []
    for line in text.splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "v":
            out.append("v " + " ".join(f"{float(c):.4f}".rstrip("0").rstrip(".") for c in parts[1:4]))
        elif parts[0] in ("o", "usemtl"):
            out.append(f"{parts[0]} {parts[1]}")
        elif parts[0] == "f":
            out.append("f " + " ".join(p.split("/")[0] for p in parts[1:]))
    return "\n".join(out) + "\n"


def module(models: dict[str, str]) -> str:
    lines = [
        "// Generated by scripts/models.py from assets/3d/models/: do not edit by hand.",
        "// Furniture models of the 3D visit (assets/js/visit3d.js), as OBJ text, by name.",
        "export default {",
    ]
    for name in sorted(models):
        lines.append(f"  '{name}': [")
        lines += [f"    '{l}'," for l in models[name].splitlines()]
        lines.append("  ].join('\\n'),")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    if "--add" in args:
        MODELS.mkdir(parents=True, exist_ok=True)
        for src in (Path(a) for a in args[args.index("--add") + 1:] if not a.startswith("--")):
            (MODELS / src.name).write_text(clean(src.read_text(encoding="utf-8")), encoding="utf-8")
            print(f"{src.name}: added")
    models = {p.stem: p.read_text(encoding="utf-8") for p in sorted(MODELS.glob("*.obj"))}
    content = module(models)
    current = MODULE.read_text(encoding="utf-8") if MODULE.exists() else ""
    if content == current:
        if check:
            print(f"{len(models)} models, module up to date.")
        return 0
    if check:
        print(f"ERROR {MODULE.relative_to(REPO_ROOT)} is not up to date (run scripts/models.py)")
        return 1
    MODULE.write_text(content, encoding="utf-8")
    print(f"{MODULE.relative_to(REPO_ROOT)}: {len(models)} models, {len(content) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
